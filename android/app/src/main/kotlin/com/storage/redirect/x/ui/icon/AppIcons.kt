private class MingCutePath(
    val data: String,
    val isStroke: Boolean,
    val cap: StrokeCap = StrokeCap.Butt,
    val join: StrokeJoin = StrokeJoin.Miter,
    val isEvenOdd: Boolean = false,
)

private fun stroke(data: String, cap: StrokeCap, join: StrokeJoin) = MingCutePath(data, isStroke = true, cap = cap, join = join)

private fun fill(data: String, isEvenOdd: Boolean = false) = MingCutePath(data, isStroke = false, isEvenOdd = isEvenOdd)

// 统一 24dp 画布与 2dp 线宽，着色交给 Icon 的 tint
private fun mingCute(source: String, vararg paths: MingCutePath): ImageVector = ImageVector.Builder(
    name = "MingCute.$source",
    defaultWidth = 24.dp,
    defaultHeight = 24.dp,
    viewportWidth = 24f,
    viewportHeight = 24f,
).apply {
    for (path in paths) {
        addPath(
            pathData = PathParser().parsePathString(path.data).toNodes(),
            pathFillType = if (path.isEvenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
            fill = if (path.isStroke) null else SolidColor(Color.Black),
            stroke = if (path.isStroke) SolidColor(Color.Black) else null,
            strokeLineWidth = 2f,
            strokeLineCap = path.cap,
            strokeLineJoin = path.join,
        )
    }
}.build()
